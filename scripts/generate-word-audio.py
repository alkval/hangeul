"""Generate a consistent Korean voice for the complete word bank.

Install edge-tts==7.2.8 in a virtual environment, then run this script.
Requires Node.js with TypeScript stripping (the same version used by npm test).
No browser runtime service, secret, or backend is required.
"""
import asyncio
import json
import subprocess
from pathlib import Path

import edge_tts

ROOT = Path(__file__).resolve().parent.parent
VOICE = 'ko-KR-SunHiNeural'
RATE = '-15%'
DESTINATION = ROOT / 'public' / 'audio' / 'words'


def word_bank():
    result = subprocess.run(
        ['node', '--experimental-strip-types', '--input-type=module', '-e',
         "import {words} from './src/words.ts';process.stdout.write(JSON.stringify(words));"],
        cwd=ROOT, capture_output=True, check=True, encoding='utf-8',
    )
    return json.loads(result.stdout)


async def main():
    words = word_bank()
    DESTINATION.mkdir(parents=True, exist_ok=True)
    semaphore = asyncio.Semaphore(3)

    async def generate(word):
        async with semaphore:
            target = DESTINATION / (word['id'] + '.mp3')
            if target.exists() and target.stat().st_size > 1000:
                return
            # Read the actual full word. Korean TTS applies sound changes itself;
            # splitting it into syllables would lose liaison and assimilation.
            temporary = target.with_suffix('.tmp.mp3')
            for attempt in range(3):
                try:
                    await asyncio.wait_for(edge_tts.Communicate(word['glyph'], VOICE, rate=RATE).save(str(temporary)), timeout=30)
                    if temporary.stat().st_size < 1000:
                        raise ValueError('Empty audio')
                    temporary.replace(target)
                    print('Audio ready:', word['glyph'], flush=True)
                    return
                except Exception as error:
                    if attempt == 2:
                        raise RuntimeError(f"Audio generation failed: {word['glyph']}") from error
                    await asyncio.sleep(1 + attempt)

    await asyncio.gather(*(generate(word) for word in words))
    # Publish the manifest only after all clips exist. Keep Unicode filenames
    # intact; URL encoding occurs in the browser, not on disk.
    ids = [word['id'] for word in words]
    manifest = '// Generated by scripts/generate-word-audio.py.\nexport const wordAudioIds: readonly string[] = ' + json.dumps(ids, ensure_ascii=False, indent=2) + ';\n'
    (ROOT / 'src' / 'word-audio-manifest.ts').write_text(manifest, encoding='utf-8', newline='\n')
    print(f'Complete: {len(words)} word clips, {VOICE}, rate {RATE}.')


if __name__ == '__main__':
    asyncio.run(main())
